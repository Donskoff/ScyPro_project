"""
Преобразует данные из списка словарей, содержащих строки в формате CSV, в строку в формате JSON.

:param data: Данные в формате списка словарей.
:return: Строка в формате JSON, представляющая данные из списка словарей.
"""

from typing import List, Dict


def decoder_csv_json(data: List[Dict[str, str]]) -> List[Dict]:
    """Преобразует данные из списка словарей, содержащих строки в формате CSV,\
    в список словарей, представляющих данные в формате JSON.

    :param data: Данные в формате списка словарей.
    :return: Список словарей, представляющих данные из списка словарей.
    """
    # Проверка на None
    if data is None:
        print("Ошибка: входные данные не могут быть None.")
        return []  # Возвращаем пустой список

    # Список для хранения преобразованных данных
    json_data: List[Dict] = []

    # Обрабатываем каждый словарь в списке
    for entry in data:
        # Извлекаем строку из первого (и единственного) ключа словаря
        csv_string = next(iter(entry.values())).strip()

        # Проверяем, что строка не пустая
        if not csv_string:
            continue  # Пропускаем пустые строки

        # Разделяем строку по символу ';'
        fields = csv_string.split(";")

        # Проверяем, что количество полей соответствует ожиданиям
        if len(fields) < 9:
            print(f"Недостаточно полей в строке: {csv_string}")
            continue  # Пропускаем строки с недостаточным количеством полей

        # Проверяем, что поле 'id' не пустое
        if not fields[0]:
            print(f"Пустое значение для 'id' в строке: {csv_string}")
            continue  # Пропускаем строки с пустым 'id'

        # Создаем словарь для преобразования в JSON
        operation = {
            "id": int(fields[0]),  # Преобразуем в целое число
            "state": fields[1],
            "date": fields[2],
            "operationAmount": {"amount": fields[3], "currency": {"name": fields[4], "code": fields[5]}},
            "description": fields[8],  # Поле "description" находится на 9-м месте (индекс 8)
            "from": fields[6],  # Поле "from" находится на 7-м месте (индекс 6)
            "to": fields[7],  # Поле "to" находится на 8-м месте (индекс 7)
        }

        # Добавляем преобразованный словарь в список
        json_data.append(operation)

    # Возвращаем список словарей
    return json_data
